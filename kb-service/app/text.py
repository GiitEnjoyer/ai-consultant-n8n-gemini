"""Нормализация русского текста: токенизация, стоп-слова, стемминг, синонимы."""

from __future__ import annotations

import re
from functools import lru_cache

import snowballstemmer

_TOKEN_RE = re.compile(r"[a-zа-яё0-9]+", re.IGNORECASE)

STOP_WORDS = frozenset(
    """
    а без более бы был была были было быть в вам вас весь во вот все всего всех вы
    где да даже для до его ее её если есть еще ещё же за здесь и из или им их к как
    ко когда кто ли либо мне может мы на над надо наш не него нее неё нет ни них но
    ну о об однако он она они оно от очень по под при про с со так также такой там
    те тем то того тоже той только том ты у уже хотя чего чей чем что чтобы чье чья
    эта эти это этот я ваш ваша ваши вашей какой какая какие можно ли мой моя хочу
    подскажите скажите пожалуйста здравствуйте добрый день вечер утро привет
    """.split()
)

# Общие слова вопросов: сами по себе не определяют тему, поэтому совпадения
# только по ним не считаются релевантными («Сколько стоит кондиционер?»).
GENERIC_WORDS = ("сколько", "стоит", "стоимость", "цена", "срок", "сроки", "долго", "время", "ремонт", "делаете", "можно")

# Синонимы раскрывают разговорные формулировки посетителей до терминов базы знаний.
SYNONYMS: dict[str, tuple[str, ...]] = {
    "стоит": ("цена", "стоимость"),
    "сколько": ("цена", "стоимость", "срок"),
    "стоимость": ("цена",),
    "прайс": ("цена", "стоимость"),
    "долго": ("срок",),
    "время": ("срок",),
    "ванная": ("санузел", "санузла"),
    "ванной": ("санузел", "санузла"),
    "туалет": ("санузел", "санузла"),
    "гарантии": ("гарантия",),
    "рассрочку": ("рассрочка", "оплата"),
    "кредит": ("рассрочка", "оплата"),
    "платить": ("оплата",),
    "адрес": ("офис", "контакты"),
    "телефон": ("контакты",),
    "работаете": ("режим", "работы"),
    "мусор": ("вывоз",),
    "дизайн": ("дизайнерский", "проект"),
}

_stemmer = snowballstemmer.stemmer("russian")


def tokenize(text: str) -> list[str]:
    """Разбивает текст на токены в нижнем регистре, приводя «ё» к «е»."""
    return [t.lower().replace("ё", "е") for t in _TOKEN_RE.findall(text)]


@lru_cache(maxsize=50_000)
def stem(word: str) -> str:
    return _stemmer.stemWord(word)


def normalize(text: str, expand_synonyms: bool = False) -> list[str]:
    """Возвращает список основ слов без стоп-слов; для запросов раскрывает синонимы."""
    tokens = [t for t in tokenize(text) if t not in STOP_WORDS and len(t) > 1]
    if expand_synonyms:
        extra = [s for t in tokens for s in SYNONYMS.get(t, ())]
        tokens.extend(extra)
    return [stem(t) for t in tokens]
